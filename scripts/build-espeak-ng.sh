#!/usr/bin/env bash
# Build third_party/espeak-ng/phonemizer.js, the text-to-phoneme module, from pinned eSpeak NG source.
#
# This script, the eSpeak NG source at ESPEAK_NG_COMMIT, Emscripten EMSCRIPTEN_VERSION and
# src/phonemizer-wrapper.js are the corresponding source of the generated module (GPL-3.0-or-later).
#
# Requirements: git, CMake, a native C/C++ compiler, and Emscripten EMSCRIPTEN_VERSION activated
# (`emsdk install 7.0.0 && emsdk activate 7.0.0 && source emsdk_env.sh`), or run it inside the
# `emscripten/emsdk:7.0.0` container image, which also provides git, CMake and a native compiler.
set -euo pipefail

ESPEAK_NG_REPOSITORY=https://github.com/espeak-ng/espeak-ng.git
# eSpeak NG master on 2024-03-25. Its English dictionary, phoneme tables, intonations, language and
# voice files are byte-identical to the data embedded in phonemizer 1.2.1, which kokoro-js 1.2.1 was
# built against; the next upstream change to that data is a5835f82 (2024-06-15).
ESPEAK_NG_COMMIT=890071ff30231883d761e4d59edabd6d69faf159
EMSCRIPTEN_VERSION=7.0.0
# GPLv3 section 5(a) date of offline-speech's changes to eSpeak NG. When a patch in
# third_party/espeak-ng/patches/ changes, update this date and the first line of every patch.
MODIFIED_DATE=2026-11-10

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
OUTPUT=$ROOT/third_party/espeak-ng/phonemizer.js

if ! command -v emcc >/dev/null; then
  echo "emcc not found: activate Emscripten $EMSCRIPTEN_VERSION first (see the header of this script)." >&2
  exit 1
fi
FOUND=$(emcc --version | sed -n 's/.* \([0-9][0-9.]*\) (.*/\1/p' | head -1)
if [ "$FOUND" != "$EMSCRIPTEN_VERSION" ]; then
  echo "Emscripten $EMSCRIPTEN_VERSION is required for a reproducible build; found $FOUND." >&2
  exit 1
fi

# eSpeak NG's phoneme compiler truncates long paths, so build in a short temporary directory.
WORK=$(mktemp -d "${TMPDIR:-/tmp}/espeak.XXXXXX")
trap 'rm -rf "$WORK"' EXIT
SRC=$WORK/src

git init -q "$SRC"
git -C "$SRC" fetch -q --depth 1 "$ESPEAK_NG_REPOSITORY" "$ESPEAK_NG_COMMIT"
git -C "$SRC" checkout -q FETCH_HEAD
[ "$(git -C "$SRC" rev-parse HEAD)" = "$ESPEAK_NG_COMMIT" ]
# Build fixes for current Emscripten; see each patch's description.
for patch in "$ROOT"/third_party/espeak-ng/patches/*.patch; do
  git -C "$SRC" apply "$patch"
done

# Optional features only affect audio synthesis; phonemes come from the core library and data.
OPTIONS=(-DCMAKE_BUILD_TYPE=Release -DUSE_MBROLA=OFF -DUSE_LIBSONIC=OFF -DUSE_LIBPCAUDIO=OFF
  -DUSE_ASYNC=OFF -DUSE_KLATT=OFF -DUSE_SPEECHPLAYER=OFF)

# 1. The data compilers run natively.
cmake -S "$SRC" -B "$WORK/native" "${OPTIONS[@]}" >/dev/null
cmake --build "$WORK/native" --target data -j "$(getconf _NPROCESSORS_ONLN)" >/dev/null

# Embed the same files as phonemizer 1.2.1: the shared phoneme data, intonations, every language and
# voice definition, and only the English dictionary.
DATA=$WORK/espeak-ng-data
mkdir -p "$DATA"
for name in phondata phonindex phontab intonations en_dict lang voices; do
  cp -R "$WORK/native/espeak-ng-data/$name" "$DATA/"
done

# 2. The library, compiled to WebAssembly. The /usr prefix makes its built-in data path
#    /usr/share/espeak-ng-data, where step 3 embeds the data.
emcmake cmake -S "$SRC" -B "$WORK/wasm" "${OPTIONS[@]}" -DCMAKE_INSTALL_PREFIX=/usr >/dev/null
cmake --build "$WORK/wasm" --target espeak-ng ucd -j "$(getconf _NPROCESSORS_ONLN)" >/dev/null

# 3. eSpeak NG's own browser bindings (emscripten/), linked into one ES module with the data embedded.
GLUE=$WORK/glue
mkdir -p "$GLUE"
cp "$SRC"/emscripten/{espeakng_glue.idl,espeakng_glue.cpp,pre.js,post.js} "$GLUE/"
(cd "$GLUE" && "$(dirname "$(command -v emcc)")/tools/webidl_binder" espeakng_glue.idl glue >/dev/null)
em++ -O3 -DESPEAK_DATA_PATH=\"/usr/share/espeak-ng-data\" -I "$GLUE" -I "$SRC/src/include/espeak-ng" \
  -I "$SRC/src/include" -c "$GLUE/espeakng_glue.cpp" -o "$GLUE/espeakng_glue.o"
em++ -O3 "$GLUE/espeakng_glue.o" "$WORK/wasm/src/libespeak-ng/libespeak-ng.a" \
  "$WORK/wasm/src/ucd-tools/libucd.a" \
  -sMODULARIZE -sEXPORT_ES6 -sEXPORT_NAME=createESpeakNG -sSINGLE_FILE -sENVIRONMENT=web,worker,node \
  -sFORCE_FILESYSTEM -sALLOW_MEMORY_GROWTH -sINCOMING_MODULE_JS_API=print,printErr \
  --embed-file "$DATA@/usr/share/espeak-ng-data" \
  --pre-js "$GLUE/pre.js" --post-js "$GLUE/glue.js" --post-js "$GLUE/post.js" \
  -o "$GLUE/espeakng.mjs"

# 4. One file for the app: the module factory, then the phonemize/list_voices wrapper.
mkdir -p "$(dirname "$OUTPUT")"
{
  echo "// Generated by scripts/build-espeak-ng.sh from eSpeak NG $ESPEAK_NG_COMMIT"
  echo "// (https://github.com/espeak-ng/espeak-ng, GPL-3.0-or-later) with Emscripten $EMSCRIPTEN_VERSION."
  echo "// Modified by offline-speech, $MODIFIED_DATE: patches 0001-0003; adapted browser packaging and phonemizer API."
  echo "// The wrapper at the end is src/phonemizer-wrapper.js, adapted from phonemizer.js (Apache-2.0)."
  # The module is one long line that also holds the embedded data; drop only its final export.
  node -e 'const s = require("fs").readFileSync(process.argv[1], "latin1"), e = "export default createESpeakNG;";
    if (!s.trimEnd().endsWith(e)) throw new Error("Unexpected Emscripten output: " + e + " not at the end");
    process.stdout.write(Buffer.from(s.trimEnd().slice(0, -e.length), "latin1"));' "$GLUE/espeakng.mjs"
  echo
  cat "$ROOT/src/phonemizer-wrapper.js"
} > "$OUTPUT"

echo "Wrote ${OUTPUT#"$ROOT"/} ($(wc -c < "$OUTPUT" | tr -d ' ') bytes, sha256 $(shasum -a 256 "$OUTPUT" | cut -c1-64))."
